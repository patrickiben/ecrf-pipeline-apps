#!/usr/bin/env python3
"""Generate the SYNTHETIC study-data domains for sample_data (deterministic, seed 42).

Run from anywhere:   python3 generate.py     (writes ae/lb/eg/vs/pe next to this file)

This is ONE cut that all three apps read from. It preserves the small worked rows used by
the case study (docs/case-study.html) and the coding/PHI traces byte-for-byte, then appends a larger set of participants so the
risk-scoring app can be assessed on bulk/varied data. Every domain carries the SAME columns it
would in a real SDTM-ish dump -- including free-text fields (AECOM / EGCOM) alongside numeric
safety values and source-system flags (ABNORMAL, CLINSIG).

EVERYTHING HERE IS SYNTHETIC. No real patient, no licensed MedDRA, no real study. The participant
IDs, terms, values and notes are invented for demonstration. `pr.csv` and `meddra_demo.csv` are
hand-authored demo/reference files and are NOT regenerated by this script -- see README.md.

To add more/varied data: widen the SUBJS range or edit ANCHORS below, then re-run (seeded, so a
given edit reproduces the same cut). If you change an anchor's expected outcome, update the
matching R-check in tests/qc_test.py.
"""
import csv, os, random

random.seed(42)
OUT = os.path.dirname(os.path.abspath(__file__))   # .../biostat_pipeline_apps/sample_data
STUDY = "PROTO-2026-X89"                            # synthetic study id (not real)

# --------------------------------------------------------------------------- #
# The worked rows shown in docs/case-study.html (first written for the retired Deck B), preserved EXACTLY for AETERM/AESEV/AESER/AECOM so the
# coding and PHI traces stay accurate. We add AELIFE (=N; none fatal), a plausible AEOUTCOME,
# and a plausible AEREL, which neither trace reads. Row 6's blank AECOM is the "missing stays
# missing" demo. None of these worked rows are fatal -- they all carry a non-fatal outcome.
# --------------------------------------------------------------------------- #
WORKED_AE = [
    ("SUBJ-3092", 1, "severe throbbing pain in back of head", "SEVERE", "Y", "POSSIBLE",
     "CRC Note: Patient Jane Miller called site cell phone (617) 555-0192 at 10:15 AM."),
    ("SUBJ-3092", 2, "feeling lightheaded when standing up", "MODERATE", "N", "UNKNOWN",
     "Patient Jane Miller tolerating well; continued Alanine 50 mg; repeat glucose 120 mg/dL."),
    ("SUBJ-1044", 3, "frequent watery bowel movements", "MODERATE", "N", "UNKNOWN",
     "Four episodes; no intervention required."),
    ("SUBJ-4110", 4, "marked prolonged heart rhythm interval", "MILD", "N", "POSSIBLE",
     "Repeat ECG ordered; subject resting comfortably."),
    ("SUBJ-5227", 5, "headache", "MILD", "N", "PROBABLE", "First episode this cycle."),
    ("SUBJ-5227", 6, "rash on forearm", "MILD", "N", "UNKNOWN", ""),   # blank AECOM on purpose
]

# The PHI clean-negative ECG row (the case study's worked example), preserved exactly for EGCOM.
WORKED_EG = ("SUBJ-1044", 1, 432, 72, "Sinus rhythm, no artifact.")

TERMS = {
    "MILD": ["Headache", "Nausea", "Dizziness", "Fatigue", "Rash", "Insomnia"],
    "MODERATE": ["Vomiting", "Diarrhoea", "ALT increased", "Hypertension", "Pyrexia", "Arthralgia"],
    "SEVERE": ["QT prolongation", "Hepatotoxicity", "Neutropenia", "Pneumonia", "Renal impairment", "Anaemia"],
    "LIFETHREATENING": ["Cardiac arrest", "Anaphylactic reaction", "Status epilepticus", "Sepsis"],
}
# SDTM-valid causality values (AEREL). No bare "Unknown": UNKNOWN is the explicit code, and
# PROBABLE/POSSIBLE/UNLIKELY are the graded relatedness levels a real study reports.
REL = ["PROBABLE", "POSSIBLE", "UNLIKELY", "UNKNOWN"]

# Identifier-free clinical notes for most bulk AECOM cells.
NOTES = ["", "Resolved without intervention.", "Monitored; no action required.",
         "Improved on supportive care.", "Ongoing; reassess next visit."]

# PHI-bearing clinical notes for a SUBSET of bulk AECOM cells -- realistic free text that hides
# direct identifiers (names, phones, MRN, DOB, ZIP) and indirect ones (initials). This exercises the
# PHI app's content-based discovery + scrubbing across many rows, not just the six worked demos.
PHI_NOTES = [
    "Patient Maria Gonzalez called site cell phone (415) 555-0132 at 9:40 AM.",
    "Contact John Smith at 800-555-0173; MRN 4471920 on file.",
    "DOB 03/14/1968 confirmed with patient; symptom onset this week.",
    "Per J.M.'s report, symptoms began after travel to the 02139 area.",
    "Patient Robert Chen (MRN A-20384) reports mild discomfort; no intervention.",
    "Family contact Lisa Wong, phone (617) 555-0148, notified per protocol.",
    "Born 1975-11-02; resides in zip 94110. Monitoring continues.",
    "Patient Daniel Okafor called at 3:15 PM from (212) 555-0166.",
    "Record #B-88213 updated; patient Tanya Reyes tolerating well.",
    "DOB 12/09/1954 verified. Patient Karen White reports improvement.",
]

def bulk_note():
    """Most bulk AECOM cells are identifier-free; ~40% carry realistic PHI so the redaction app is
    exercised across many rows, not just the worked demos."""
    return random.choice(PHI_NOTES) if random.random() < 0.4 else random.choice(NOTES)

SUBJS = [f"SUBJ-{n}" for n in range(9001, 9049)]    # 48 bulk participants: 6 anchors + 42 seeded

# Explicit anchor profiles (the teaching cases the QC harness asserts on).
ANCHORS = {
    "SUBJ-9001": dict(ae=[("Cardiac arrest", "LIFETHREATENING", "Y", "PROBABLE"),
                          ("QT prolongation", "SEVERE", "Y", "PROBABLE"),
                          ("Hepatotoxicity", "SEVERE", "Y", "PROBABLE")],
                      life="N", labs={"ALT": 6.5, "AST": 4.2}, qtc=530, vs={"SYSBP": 190}),
    "SUBJ-9002": dict(ae=[("Hepatotoxicity", "SEVERE", "Y", "PROBABLE"),
                          ("Neutropenia", "SEVERE", "Y", "POSSIBLE")],
                      life="N", labs={"ALT": 5.1, "AST": 3.8}, qtc=470, vs={}),
    "SUBJ-9003": dict(ae=[("Pneumonia", "SEVERE", "Y", "POSSIBLE"),
                          ("Vomiting", "MODERATE", "N", "UNKNOWN")],
                      life="N", labs={"CREAT": 1.8}, qtc=None, vs={}),
    "SUBJ-9013": dict(ae=[("ALT increased", "MODERATE", "N", "POSSIBLE")],
                      life="N", labs={"ALT": 7.2, "AST": 5.0}, qtc=None, vs={}),   # lab-driven
    "SUBJ-9014": dict(ae=[("QT prolongation", "MODERATE", "N", "POSSIBLE")],
                      life="N", labs={}, qtc=505, vs={}),                          # QTc-driven
    "SUBJ-9015": dict(ae=[("Anaphylactic reaction", "LIFETHREATENING", "Y", "PROBABLE")],
                      life="Y", outcome="DIED", labs={}, qtc=None, vs={}),          # genuinely FATAL (AEOUTCOME=DIED)
}

# Non-fatal AE outcomes for seeded participants -- weighted toward recovered so the cut looks like a
# real study. AELIFE=Y always pairs with AEOUTCOME=DIED; life-threatening SEVERITY alone never does.
NONFATAL_OUTCOMES = ["RECOVERED", "RECOVERED", "RECOVERED", "NOT RECOVERED", "RECOVERING", "NOT KNOWN"]

# Source-system flag thresholds (x ULN / absolute) used to derive ABNORMAL and CLINSIG.
ULN = {"ALT": 40.0, "AST": 35.0, "CREAT": 1.2}
SAP_MULT = {"ALT": 3.0, "AST": 3.0, "CREAT": 1.5}     # clinically-significant stopping multiples
QTC_ABNORMAL, QTC_CLINSIG = 460, 500                  # ms
VS_LIMITS = {                                          # param: (abnormal_if_outside, clinsig_limit)
    "SYSBP": ((90, 140), 180), "DIASTP": ((60, 90), 110), "TEMPC": ((35.0, 37.5), 38.5),
}

def rand_aes(n):
    out = []
    for _ in range(n):
        sev = random.choices(["MILD", "MODERATE", "SEVERE"], weights=[0.6, 0.3, 0.1])[0]
        term = random.choice(TERMS[sev])
        ser = "Y" if (sev == "SEVERE" and random.random() < 0.5) else "N"
        out.append((term, sev, ser, random.choice(REL)))
    return out

ae_rows, lb_rows, eg_rows, vs_rows, pe_rows = [], [], [], [], []

# --- worked AE rows first (exact), then bulk participants ------------------- #
# Worked rows are all non-fatal: AELIFE=N with a recovered outcome.
for subj, seq, term, sev, ser, rel, com in WORKED_AE:
    ae_rows.append([STUDY, subj, seq, term, sev, ser, "N", "RECOVERED", rel, com])

pe_pool = ["Tachycardia", "Hepatomegaly", "Rash", "Peripheral edema", "Jaundice",
           "Lymphadenopathy", "Murmur", "Dry cough"]
# anchor participants get a couple of Present findings consistent with their profile; others mostly Absent
PE_PRESENT = {"SUBJ-9001": ["Tachycardia", "Hepatomegaly"], "SUBJ-9002": ["Hepatomegaly"],
              "SUBJ-9005": ["Rash"], "SUBJ-9014": ["Hepatomegaly"]}

for s in SUBJS:
    if s in ANCHORS:
        prof = ANCHORS[s]
        aes, labs, qtc, vitals, life = prof["ae"], prof["labs"], prof["qtc"], prof["vs"], prof["life"]
        outcome_override = prof.get("outcome")   # explicit teaching-case outcome (e.g. SUBJ-9015 DIED)
    else:
        n_ae = random.randint(1, 5)
        aes = rand_aes(n_ae)
        outcome_override = None
        labs = {}
        if random.random() < 0.5:
            for a in random.sample(["ALT", "AST", "CREAT"], k=random.randint(1, 2)):
                labs[a] = round(random.uniform(1.1, 3.4), 1)   # mostly sub-threshold; some breach SAP multiple
        qtc = random.randint(395, 505) if random.random() < 0.6 else None
        vitals = {}
        if random.random() < 0.4: vitals["SYSBP"] = random.randint(118, 172)
        if random.random() < 0.2: vitals["DIASTP"] = random.randint(65, 95)
        life = "N"

    # AEOUTCOME backs the fatal flag with explicit evidence: AELIFE=Y pairs with DIED; a
    # life-threatening SEVERITY (e.g. SUBJ-9001's cardiac arrest) stays non-fatal unless it died.
    for i, (term, sev, ser, rel) in enumerate(aes, 1):
        if life == "Y":
            oc = "DIED"
        elif outcome_override:
            oc = outcome_override
        else:
            oc = random.choice(NONFATAL_OUTCOMES)
        ae_rows.append([STUDY, s, i, term, sev, ser, life, oc, rel, bulk_note()])

    # labs: value = ratio x ULN; ABNORMAL if above ULN, CLINSIG if past the SAP multiple
    for analyte, ratio in labs.items():
        uln = ULN[analyte]
        abn = "Y" if ratio > 1.0 else "N"
        clinsig = "Y" if ratio > SAP_MULT.get(analyte, 9e9) else "N"
        lb_rows.append([s, analyte, round(ratio * uln, 1), uln, abn, clinsig])

    # ECG: keep the worked clean row for SUBJ-1044; anchors/seeded carry a QTc value
    if qtc is not None:
        eg_rows.append([STUDY, s, 1, qtc, random.randint(60, 95),
                        "Y" if qtc > QTC_ABNORMAL else "N",
                        "Y" if qtc >= QTC_CLINSIG else "N",
                        "Prolonged QTc noted; cardiology consulted." if qtc >= QTC_CLINSIG
                        else ("QTc borderline; repeat ECG ordered." if qtc > QTC_ABNORMAL
                              else "QTc within limits.")])

    for par, val in vitals.items():
        (lo, hi), clinsig_lim = VS_LIMITS[par]
        abn = "Y" if not (lo <= val <= hi) else "N"
        vs_rows.append([s, par, val, abn, "Y" if val >= clinsig_lim else "N"])

    # physical exam: real findings with Present/Absent -- no "Normal exam" pseudo-finding.
    present = PE_PRESENT.get(s, [])
    for decod in random.sample(pe_pool, k=random.randint(1, 3)):
        pe_rows.append([s, decod, "Present" if decod in present else "Absent"])

# the worked clean-negative ECG row (exact EGCOM) -- appended so it is preserved verbatim
subj, seq, qtc, hr, com = WORKED_EG
eg_rows.insert(0, [STUDY, subj, seq, qtc, hr, "N", "N", com])

def write(name, header, rows):
    with open(os.path.join(OUT, name), "w", newline="") as f:
        w = csv.writer(f); w.writerow(header); w.writerows(rows)

# Every domain carries a visit/timepoint dimension (AVISIT label + VISITNUM index), like real SDTM-ish
# dumps. Assigned deterministically from ROW POSITION -- deliberately NOT the seeded RNG stream -- so
# adding this column never perturbs any existing value, anchor participant, or PHI-bearing note in the cut.
VISITS = 4
def _visit(i):
    n = (i % VISITS) + 1
    return f"V{n}", n
def add_visits(rows, at):
    out=[]
    for i,r in enumerate(rows):
        lab,n=_visit(i); r=list(r); r.insert(at,lab); r.insert(at+1,n); out.append(r)
    return out

write("ae.csv", ["STUDYID","USUBJID","AVISIT","VISITNUM","AESEQ","AETERM","AESEV","AESER","AELIFE","AEOUTCOME","AEREL","AECOM"], add_visits(ae_rows,2))
write("lb.csv", ["USUBJID","AVISIT","VISITNUM","LBTESTCD","LBSTRESN","LBNRHI","ABNORMAL","CLINSIG"], add_visits(lb_rows,1))
write("eg.csv", ["STUDYID","USUBJID","AVISIT","VISITNUM","EGSEQ","EGQTC","EGHRR1","ABNORMAL","CLINSIG","EGCOM"], add_visits(eg_rows,2))
write("vs.csv", ["USUBJID","AVISIT","VISITNUM","VSPAR","VSSTRESN","ABNORMAL","CLINSIG"], add_visits(vs_rows,1))
write("pe.csv", ["USUBJID","AVISIT","VISITNUM","PEDECOD","PEFIND"], add_visits(pe_rows,1))

print(f"ae={len(ae_rows)} lb={len(lb_rows)} eg={len(eg_rows)} vs={len(vs_rows)} "
      f"pe={len(pe_rows)} bulk_subjects={len(SUBJS)} -> {OUT}")
